interface I18nContextValue {
  lang: Lang;
  setLang: (l: Lang) => void;
  /// 翻译：支持 {placeholder} 插值，如 t('key', { name: 'x' })
  t: (key: string, params?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nContextValue>({
  lang: 'zh',
  setLang: () => {},
  t: (key) => DICT.zh[key] ?? key,
});

/// i18n Provider：语言持久化到 localStorage
export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    const saved = localStorage.getItem('talk2esp-lang');
    return saved === 'en' ? 'en' : 'zh';
  });
  const setLang = (l: Lang) => {
    setLangState(l);
    localStorage.setItem('talk2esp-lang', l);
  };
  const t = (key: string, params?: Record<string, string | number>) => {
    let s = DICT[lang][key] ?? DICT.zh[key] ?? key;
    if (params) {
      for (const [k, v] of Object.entries(params)) {
        s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
      }
    }
    return s;
  };
  return (
    <I18nContext.Provider value={{ lang, setLang, t }}>
      {children}
    </I18nContext.Provider>
  );
}

/// useI18n hook：获取翻译函数
export function useI18n() {
  return useContext(I18nContext);
}
